package model;

/**
 * Represents the political wing or spectrum to which a candidate may belong.
 * This classification helps in analyzing political behaviors and tendencies within the simulation.
 */
public enum PoliticalWing {
    /**
     * Represents left-wing political ideologies typically associated with progressive policies,
     * equality, and state intervention in the economy.
     */
    LEFT_WING,

    /**
     * Represents right-wing political ideologies typically associated with
     * free market capitalism and reduced government intervention in the economy.
     */
    RIGHT_WING
}
package model;

/**
 * Represents the general political orientation of a candidate,
 * categorizing political beliefs into broad, commonly understood categories.
 */
public enum PoliticalOrientation {
    /**
     * Represents liberal political orientation, often aligned with progressive and reformist policies,
     * emphasizing individual rights and freedoms.
     */
    LIBERAL,

    /**
     * Represents conservative political orientation, often associated with maintaining traditional values
     * and skepticism of change without proven efficacy.
     */
    CONSERVATIVE
}